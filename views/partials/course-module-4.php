<div class="module-concept">
  <h2>💡 The Concept</h2>
  <h3>Entity-First SEO</h3>
  <p>Modern search engines understand entities (real-world things: people, places, concepts) and their relationships. Optimising for entities means: mentioning related concepts, citing authoritative sources, using structured data, and being mentioned across the web in context. Keywords are how you discover intent; entities are how you establish authority.</p>
  <h3>Topical Authority &amp; Cluster Architecture</h3>
  <p>Google rewards sites that comprehensively cover a topic. Architecture: one pillar page (comprehensive overview) + multiple cluster pages (specific subtopics) + strong internal linking. AI accelerates the research and planning phase from weeks to hours.</p>
  <h3>AI Keyword Research: Beyond Metrics</h3>
  <p>AI-enhanced research adds: search intent analysis (what users want at each funnel stage), semantic cluster mapping (which keywords belong together), and question mining (PAA questions, Reddit threads, Quora — what people ask that no one answers well).</p>
  <h3>Content Briefs with AI</h3>
  <p>A complete AI-generated content brief: target keyword + intent, recommended structure, entities to mention, questions to answer, competitor gaps, suggested word count, and internal link map. A good brief means any writer — human or AI — produces a consistent result.</p>
  <h3>Technical SEO + AI</h3>
  <p>AI can: analyse crawl data and flag issues, generate schema markup at scale, write 500 meta descriptions in minutes, and identify internal linking opportunities across large sites. It cannot replace technical judgment — it amplifies it.</p>
  <h3>Content Refresh with AI</h3>
  <p>Pages that ranked but are declining are the highest-ROI SEO opportunity. AI can: identify what's missing vs. current ranking pages, suggest new sections, update outdated statistics, and improve structure for featured snippets.</p>
</div>
