<div class="module-qa">
  <h2>🔍 QA: How to Judge if AI's Output is Good</h2>
  <ul>
    <li>Does it cite specific facts? Can you verify them? (Hallucination check)</li>
    <li>Does it sound like your brand? Or generic?</li>
    <li>Would a real expert say something this confident without caveats?</li>
    <li>Is there anything legally, medically, or financially sensitive that needs expert review?</li>
  </ul>
