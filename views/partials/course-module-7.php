<div class="module-concept">
  <h2>💡 The Concept</h2>
  <h3>Campaign Architecture in the AI Era</h3>
  <p>The marketer's job has shifted from: "Set the right bids and targeting" → "Provide the right signals and creative inputs." AI handles distribution and optimisation. You handle strategy, creative direction, and conversion signal quality.</p>
  <h3>Google Performance Max</h3>
  <p>PMax consolidates all Google inventory (Search, Shopping, YouTube, Display, Discover, Gmail) into one AI-managed campaign. It works best when you: provide rich creative assets (headlines, images, videos in multiple formats), feed high-quality conversion data (Google Tag + GA4 properly configured), use audience signals (not hard targeting, but hints), and give it 4+ weeks of learning before making changes.</p>
  <h3>Google AI Max for Search</h3>
  <p>AI Max expands traditional search campaigns with AI — it can match queries semantically beyond exact/phrase match, generate ad copy variations, and adjust bids more aggressively. Requires careful monitoring of search term reports to prevent waste on irrelevant queries.</p>
  <h3>Meta Advantage+ Campaigns</h3>
  <p>Meta's Advantage+ Shopping Campaigns (ASC) automated targeting and creative delivery based on conversion data. The marketer's role: provide strong creative inputs (images, videos, copy), define the product catalog, set clear campaign objectives, and monitor creative fatigue. Audience targeting is largely unnecessary — Meta's AI does it better with data.</p>
  <h3>AI Creative Generation &amp; Testing</h3>
  <p>Use AI to: generate 10+ headline variations for A/B testing, write multiple ad copy angles (rational vs. emotional, problem vs. solution, social proof), and create image brief directions for visual testing. Meta's Advantage+ Creative can automatically test variations if you provide assets.</p>
  <h3>Budget, CAC, ROAS &amp; Scaling</h3>
  <p>Scaling a profitable campaign: increase budget by max 20–30% per week (aggressive increases reset learning). Monitor efficiency metrics (ROAS, CAC, CPL) before and after changes. Know your target CPL and ROAS before you start — without these, you can't evaluate AI campaign performance.</p>
</div>
<div class="module-workflow">
  <h2>⚙️ AI Campaign Workflow</h2>
  <pre class="code-block">1. Define conversion goal + target CPL/ROAS
2. Set up conversion tracking (Google Tag + GA4 + Meta Pixel)
3. Create creative assets (AI-assisted, human direction)
4. Set up campaign with audience signals (not hard targeting)
5. Let AI learn for 4 weeks (minimal changes)
6. Analyse: What's working? What creative is performing?
7. Scale budget on winners (max 30%/week)
8. Refresh creative when frequency/fatigue rises</pre>
</div>
