<div class="module-concept">
  <h2>💡 The Concept</h2>
  <h3>GEO: Generative Engine Optimisation</h3>
  <p>GEO is the practice of optimising your content to be retrieved and cited by AI answer engines (ChatGPT Search, Perplexity, Google AI Overviews, Gemini). It differs from traditional SEO in that the "ranking" is a citation in an AI-generated answer, not a blue link on page 1.</p>
  <h3>How Google AI Overviews Work</h3>
  <p>Google's AI Overviews use a multi-step process: identify the query type, retrieve candidate pages, synthesise an answer, and cite sources. Pages get cited when they: clearly answer the specific question, use structured formatting (headers, lists, definitions), have entity authority (Google knows who you are), and are cited elsewhere on the web.</p>
  <h3>ChatGPT Search &amp; Perplexity</h3>
  <p>OpenAI's OAI-SearchBot and Perplexity's crawler index and rank pages similarly to traditional search but with emphasis on: recency, authoritative sources, clear direct answers, and structured data. Getting indexed by these crawlers is step one — check your robots.txt doesn't block them.</p>
  <h3>Entity Signals for AI Visibility</h3>
  <p>AI answer engines trust entities it recognises. Build your entity profile: consistent brand name and description across Wikipedia (if eligible), Wikidata, Google Business Profile, LinkedIn, industry directories, press mentions, and structured data on your website (Organization schema, Author schema, FAQ schema).</p>
  <h3>Content Structure for AI Retrieval</h3>
  <p>AI engines prefer content structured to answer specific questions: clear question-as-heading, direct answer in first paragraph, supporting detail, and sourced claims. Think of each section as a potential snippet, not just part of a flowing article.</p>
  <h3>Tracking AI Visibility</h3>
  <p>Systematic tracking: test 50 target queries in ChatGPT, Perplexity, and Google AI Overviews monthly. Record whether you're cited, where you rank in citations, and which competitor is cited instead. This gap analysis drives your GEO action plan.</p>
</div>
