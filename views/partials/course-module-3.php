<div class="module-concept">
  <h2>💡 The Concept</h2>

  <h3>Customer Research with AI</h3>
  <p>AI can synthesise patterns across thousands of data points: customer reviews, Reddit threads, forum posts, support tickets, and interview transcripts. The goal is to surface real customer language — the exact words they use to describe their problems, not your internal jargon.</p>
  <p><strong>Jobs-to-Be-Done:</strong> Customers don't buy products — they hire them to do a job. AI identifies functional, emotional, and social jobs by analysing patterns in customer language.</p>

  <h3>Competitor Analysis</h3>
  <p>Use AI to systematically analyse competitor content: their top-performing pages, their positioning claims, their review sentiments, their content gaps. Feed competitor pages directly into Claude and ask for structured analysis.</p>

  <h3>Review Mining</h3>
  <p>Amazon reviews, G2, Capterra, Google reviews — these are gold mines of customer language. Feed 50–100 reviews into Claude: <em>"Identify the top 5 pain points, the top 5 jobs being done, and the exact phrases customers use to describe each."</em></p>

  <h3>Market Gap Analysis</h3>
  <p>Combine competitor analysis with search data to find: topics competitors rank for but handle poorly, questions no one answers well, and positioning angles no competitor owns.</p>

  <h3>Messaging Framework</h3>
  <p>Once you have customer language and competitor positioning, AI helps you build a differentiated message: who you're for, what problem you solve, why you're different, and what transformation you deliver — in customer language, not company speak.</p>
</div>

<div class="module-workflow">
  <h2>⚙️ AI Research Workflow</h2>
